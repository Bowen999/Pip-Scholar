let lang = 'zh';
const listeners = new Set();

export const getLang = () => lang;
export const locale = () => (lang === 'zh' ? 'zh-CN' : 'en-US');

export function t(key, vars = {}) {
  const value = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? `{${name}}`);
}

// 未翻译的学科名（新增学科）原样显示
export const category = (name) => (STRINGS[lang][`cat.${name}`] ?? name);

export const fmt = (n) => (n == null ? '—' : new Intl.NumberFormat(locale()).format(n));
export const fmtDate = (iso) => new Intl.DateTimeFormat(locale(), { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(iso));

export function onLangChange(fn) { listeners.add(fn); }

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'zh';
  try { localStorage.setItem('pip-scholar.lang', lang); } catch { /* 隐私模式 */ }
  document.documentElement.lang = locale();
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  for (const el of document.querySelectorAll('[data-lang]')) el.setAttribute('aria-pressed', String(el.dataset.lang === lang));
  listeners.forEach((fn) => fn(lang));
}

export function initialLang() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  let saved = null;
  try { saved = localStorage.getItem('pip-scholar.lang'); } catch { /* 隐私模式 */ }
  return fromUrl || saved || (navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en');
}
